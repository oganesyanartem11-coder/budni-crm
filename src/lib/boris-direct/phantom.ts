// Фантом-правило (ШАГ 3б).
//
// До фикса фронта (коммит b669b35, выкат 2026-07-05) клиентский reachGoal
// «заявка» срабатывал ДАЖE на неуспешной отправке (POST мог упасть, а цель
// в Метрике уже зажглась). Значит Метрика-достижения ДО фикса — под подозрением
// на фантом/двойной сабмит. В ПОФРАЗНОЙ экономике такие достижения весят 0 —
// КРОМЕ подтверждённых владельцем конвертеров (converters.ts).
//
// Сырые данные НЕ трогаем и НЕ удаляем — правило влияет только на ВЕС в
// агрегации/суждении, не на факты в БД/снапшотах.

import { isRegisteredConverter } from './converters'

/**
 * Дата фикса фронта (reachGoal только после ответа 2xx), МСК 'YYYY-MM-DD'.
 * Достижения строго РАНЬШЕ этой даты — под подозрением на фантом.
 */
export const FRONTEND_FIX_DATE_MSK = '2026-07-05'

/**
 * Вес достижения цели в пофразной экономике: 1 — засчитываем, 0 — фантом.
 * - дата ≥ фикса фронта → 1 (фронт уже честный);
 * - подтверждённый конвертер → 1 (истина владельца, приоритет над снапшотами);
 * - иначе (дата < фикса и не конвертер) → 0 (возможный фантом до фикса).
 * Сравнение дат — лексикографическое по 'YYYY-MM-DD' (корректно для ISO-дат).
 */
export function phantomWeight(dateMsk: string, phrase?: string | null): 0 | 1 {
  if (dateMsk >= FRONTEND_FIX_DATE_MSK) return 1
  if (isRegisteredConverter(phrase)) return 1
  return 0
}

/** Достижение — вероятный фантом (вес 0)? Обёртка для читаемости в вызывающем коде. */
export function isLikelyPhantom(dateMsk: string, phrase?: string | null): boolean {
  return phantomWeight(dateMsk, phrase) === 0
}

// Гео-логика суждений Бориса-Директа.
//
// Зона доставки = Москва (213) + Московская область (1). Города МО
// (Электросталь, Балашиха и т.п.) — ЦЕЛЕВЫЕ, НЕ кандидаты в минус-гео.
// Вне-зонные города (Благовещенск, Элиста, другие регионы) — структурный мусор.
//
// ВАЖНО: это ЭВРИСТИКА-ПОМОЩНИК, а НЕ полный справочник. Судим по ТЕКСТУ
// запроса — у поисковых запросов нет RegionId. Списки городов заведомо
// НЕПОЛНЫ: длинный хвост добивает LLM-классификатор структурного мусора,
// здесь — уверенные/названные владельцем случаи + защита городов МО от
// ошибочного гео-минуса. Чистые функции, без сети и БД.


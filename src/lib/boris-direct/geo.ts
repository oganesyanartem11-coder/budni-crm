export type GeoZone = 'in_zone' | 'out_of_zone' | 'unknown'

/**
 * Нормализация под гео-матчинг: нижний регистр, ё→е, всё не буквенно-цифровое
 * (операторы Директа, пунктуация, дефисы) → пробел, схлопывание пробелов.
 * Дефис→пробел, чтобы «наро-фоминск»/«ростов-на-дону» матчились как многословные.
 */
function normGeo(s: string): string {
  return s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}


/** Список названий → { одиночные токены; многословные подстроки } (нормализовано). */
function buildCitySets(names: string[]): { single: Set<string>; multi: string[] } {
  const single = new Set<string>()
  const multi: string[] = []
  for (const raw of names) {
    const n = normGeo(raw)
    if (!n) continue
    if (n.includes(' ')) multi.push(n)
    else single.add(n)
  }
  return { single, multi }
}

const MO_CITIES = buildCitySets(MO_CITY_NAMES)
const OUT_CITIES = buildCitySets(OUT_CITY_NAMES)

/** Есть ли в запросе город из набора: одиночные — по токену, многословные — по подстроке. */
function hasCity(
  normQuery: string,
  tokens: Set<string>,
  cities: { single: Set<string>; multi: string[] }
): boolean {
  for (const t of tokens) if (cities.single.has(t)) return true
  for (const m of cities.multi) if (normQuery.includes(m)) return true
  return false
}

/** Сигнал Москвы/МО: москва/москве (москв*), московская (москов*), подмосковье, мск. */
function hasMoscowSignal(tokens: Set<string>): boolean {
  for (const t of tokens) {
    if (
      t.startsWith('москв') || // москва / москве / москвы
      t.startsWith('москов') || // московская / московской / московскую
      t.startsWith('подмосков') || // подмосковье / подмосковный
      t === 'мск'
    ) {
      return true
    }
  }
  return false
}

/**
 * Гео-зона поискового запроса по его ТЕКСТУ:
 *  - 'in_zone'     — Москва/МО (в т.ч. города МО: Электросталь и т.п.) — ЦЕЛЬ;
 *  - 'out_of_zone' — другой регион (Благовещенск, Элиста…) — структурный мусор;
 *  - 'unknown'     — города в тексте нет ИЛИ противоречие (и Москва, и вне-зонный
 *                    город) → судить не берёмся, решает LLM/владелец.
 */
export function classifyQueryGeo(query: string): GeoZone {
  const n = normGeo(query)
  if (!n) return 'unknown'
  const tokens = new Set(n.split(' '))
  const inZone = hasMoscowSignal(tokens) || hasCity(n, tokens, MO_CITIES)
  const outZone = hasCity(n, tokens, OUT_CITIES)
  if (inZone && !outZone) return 'in_zone'
  if (outZone && !inZone) return 'out_of_zone'
  return 'unknown'
}

const GEO_REASON_RE =
  /вне зон|вне москв|не москв|не в москв|друг\S* регион|друг\S* город|за предел|област|регион|гео/i

/**
 * Похоже ли текстовое обоснование LLM на ГЕО-мотив минуса (город/регион вне
 * Москвы/МО). Нужно, чтобы ЗАЩИТИТЬ целевые города МО: если LLM хочет
 * заминусить in_zone-запрос по гео-мотиву — перехватываем (город МО не
 * кандидат в минус-гео), уводим владельцу. Безопасно: ложные срабатывания
 * лишь отправляют кандидата владельцу вместо авто-минуса.
 */
export function isGeoMinusReason(reason: string | undefined | null): boolean {
  if (!reason) return false
  return GEO_REASON_RE.test(reason.replace(/ё/g, 'е'))
}

/**
 * Машинные коды причин решений Бориса-Директа (фаза 0 полигона).
 *
 * Каждое существенное решение/диагноз мозга несёт код причины + факторы-цифры.
 * Это НЕ меняет поведение — только делает рассуждение проверяемым: полигон
 * сравнивает код с истинной причиной ситуации, отсекая «угадал ход не по той
 * причине». Свободный текст остаётся для людей, код — для машинной оценки.
 *
 * Словарь фиксированный; новые коды добавлять сюда (аддитивно), не выдумывать
 * строки на месте. Зеркало для полигона: sim/types.ts (ReasonCode).
 */

export const REASON_CODES = [
  'DATA_NO_CONV', // показы/расход без конверсий за период
  'STRUCTURAL_TRASH', // структурный мусор (чужой бренд, вне гео, не наша услуга)
  'DISPUTED_MINUS', // спорный минус — предложением владельцу
  'PROVEN_CONVERTER_VOLUME', // доказанный конвертер — дать объём (TV75)
  'CORE_LOWER_BLOCK', // ядро — вход в нижний блок (TV>=55)
  'TAIL_MIN_TV', // хвост — минимальный уровень (TV15)
  'AUCTION_ABOVE_CEILING', // вход дороже потолка 400 ₽ — держаться
  'QUARANTINE_HOLD', // карантин — только наблюдать
  'NOISE_HOLD', // статистический шум / микрошум — не действовать
  'SEASONAL_DIP_HOLD', // сезонный/недельный провал — не паниковать
  'AD_TEXT_PROBLEM', // CTR низкий при нормальной позиции — вопрос к тексту объявления
  'POSITION_TOO_LOW', // позиция низкая — вопрос к ставке
  'LOW_COVERAGE', // мало показов — охват/ждать
  'FORM_DROPOFF', // визиты качественные, отвал на форме — оффер/форма, не трафик
  'BOT_TRAFFIC', // клики без визитов / мгновенные отказы — бот
  'DATA_MISMATCH', // источники данных противоречат — зафлагать, не выбирать молча
  'REGIME_CHANGE', // мир изменился — прежний вывод устарел
  'EXPLORATION', // разведка недооткрученного
  'CIRCUIT_BREAKER', // предохранитель: пачка правок вне паттерна
  'EMERGENCY_SUSPEND', // катастрофа расхода — аварийная остановка
  'ANOMALY_ALERT', // прочая аномалия
] as const

export type ReasonCode = (typeof REASON_CODES)[number]

/**
 * Машинная запись решения (кладётся в ProcessResult.decisions и в payload
 * лога действий; БД-миграции не требует — это Json).
 */
export interface DecisionRecord {
  type: 'bid' | 'minus' | 'hold' | 'proposal' | 'suspend' | 'alert' | 'diagnosis'
  targetType: 'keyword' | 'query' | 'adgroup' | 'campaign'
  targetId: string
  /** Короткое человекочитаемое описание (для разбора ошибок полигона). */
  summary: string
  reasonCode: ReasonCode
  /** Цифры, на которые опёрлось решение (показы, клики, cpl, tv и т.п.). */
  factors: Record<string, number | string>
}
